use crate::emitter::ir::*;
use crate::emitter::parse::to_pascal;
use proc_macro2::TokenStream;
use quote::{format_ident, quote};

pub fn emit(ir: &Ir) -> String {
    {
        let mut seen_names: Vec<&str> = Vec::new();
        for t in &ir.types {
            debug_assert!(
                !seen_names.contains(&t.name.as_str()),
                "duplicate TypeDef name `{}` — two schema names PascalCase to the same Rust ident",
                t.name,
            );
            seen_names.push(&t.name);
        }
    }
    // Structs used as `#[serde(tag = "type")]` variants of the webhook union:
    // internal tagging consumes their `type` field from the content buffer on
    // read, so it must default; the enum tag re-emits it on write.
    let payload_names: std::collections::HashSet<&str> = ir
        .webhook_events
        .iter()
        .map(|v| v.payload.as_str())
        .collect();
    let mut items = TokenStream::new();
    for t in &ir.types {
        items.extend(emit_type(t, &payload_names));
    }
    if !ir.webhook_events.is_empty() {
        // The synthesized union is `WebhookPayload`; `WebhookEvent` is a real
        // schema (the delivery-log record) and must keep that name.
        debug_assert!(
            !ir.types.iter().any(|t| t.name == "WebhookPayload"),
            "synthesized union name `WebhookPayload` collides with a schema-derived type",
        );
        {
            let mut seen_variants: Vec<&str> = Vec::new();
            let mut seen_wire: Vec<&str> = Vec::new();
            for v in &ir.webhook_events {
                debug_assert!(
                    !seen_variants.contains(&v.variant.as_str()),
                    "duplicate WebhookPayload variant ident `{}`",
                    v.variant,
                );
                debug_assert!(
                    !seen_wire.contains(&v.wire_type.as_str()),
                    "duplicate WebhookPayload wire_type `{}`",
                    v.wire_type,
                );
                seen_variants.push(&v.variant);
                seen_wire.push(&v.wire_type);
            }
        }
        let vs = ir.webhook_events.iter().map(|v| {
            let variant_ident = format_ident!("{}", v.variant);
            let payload_ident = format_ident!("{}", v.payload);
            let wire = &v.wire_type;
            quote! { #[serde(rename = #wire)] #variant_ident(#payload_ident) }
        });
        items.extend(quote! {
            #[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
            #[serde(tag = "type")]
            pub enum WebhookPayload { #(#vs),* }
        });
    }
    let file: syn::File = syn::parse2(quote! {
        #![allow(clippy::all, dead_code, non_camel_case_types)]
        #items
    })
    .expect("emitted tokens parse as a file");
    let body = prettyplease::unparse(&file);
    // prettyplease drops free-standing comments, so inject the banner after the
    // inner attribute (which must stay first in the file).
    let banner = "// Generated by `cargo xtask generate`. DO NOT EDIT.\n";
    match body.split_once('\n') {
        Some((attr, rest)) if attr.starts_with("#![") => format!("{attr}\n{banner}{rest}"),
        _ => format!("{banner}{body}"),
    }
}

fn doc_attr(doc: &Option<String>) -> TokenStream {
    match doc {
        Some(d) if !d.is_empty() => {
            let line = format!(" {d}");
            quote! { #[doc = #line] }
        }
        _ => TokenStream::new(),
    }
}

fn emit_type(t: &TypeDef, payload_names: &std::collections::HashSet<&str>) -> TokenStream {
    let name = format_ident!("{}", t.name);
    match &t.kind {
        TypeKind::Struct(fields) => {
            let self_name = t.name.as_str();
            let tag_consumed = payload_names.contains(self_name);
            let doc = doc_attr(&t.doc);
            let fs = fields
                .iter()
                .map(|f| emit_field(f, self_name, tag_consumed));
            quote! {
                #doc
                #[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
                pub struct #name { #(#fs),* }
            }
        }
        TypeKind::StringEnum(variants) => {
            let mut seen_idents: Vec<&str> = Vec::new();
            for v in variants {
                debug_assert!(
                    !seen_idents.contains(&v.name.as_str()),
                    "duplicate enum variant ident `{}` produced by value `{}`",
                    v.name,
                    v.rename.as_deref().unwrap_or(&v.name),
                );
                seen_idents.push(&v.name);
            }
            let vs = variants.iter().map(|v| {
                let id = format_ident!("{}", v.name);
                let rename = v.rename.as_ref().map(|r| quote! { #[serde(rename = #r)] });
                quote! { #rename #id }
            });
            quote! {
                #[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
                pub enum #name { #(#vs),* }
            }
        }
        TypeKind::TaggedUnion { tag, variants } => {
            let vs = variants.iter().map(|v| {
                let id = format_ident!("{}", v.name);
                let ty = format_ident!("{}", v.ty);
                let rename = v.rename.as_ref().map(|r| quote! { #[serde(rename = #r)] });
                quote! { #rename #id(#ty) }
            });
            quote! {
                #[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
                #[serde(tag = #tag)]
                pub enum #name { #(#vs),* }
            }
        }
        TypeKind::Alias(inner) => {
            let ty = emit_rust_type(inner);
            quote! { pub type #name = #ty; }
        }
    }
}

/// Rust keywords that need a raw-identifier (`r#`) escape when used as a field name.
const RUST_KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return",
    "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where", "while",
    "async", "await", "dyn", "abstract", "become", "box", "do", "final", "macro", "override",
    "priv", "typeof", "unsized", "virtual", "yield", "try", "self", "Self",
];

fn field_ident(name: &str) -> proc_macro2::Ident {
    if RUST_KEYWORDS.contains(&name) {
        format_ident!("r#{}", name)
    } else {
        format_ident!("{}", name)
    }
}

fn emit_field(f: &Field, self_name: &str, tag_consumed: bool) -> TokenStream {
    let name = field_ident(&f.name);
    let ty = emit_rust_type(&box_self_refs(&f.ty, self_name));
    let rename = f.rename.as_ref().map(|r| quote! { #[serde(rename = #r)] });
    // The discriminator field of an internally-tagged webhook payload: serde
    // strips it from the content on read and re-emits it via the enum tag, so it
    // must default on read and be skipped on write (this supersedes the normal
    // optional handling).
    let serde_attr = if tag_consumed && f.name == "type" {
        quote! { #[serde(default, skip_serializing)] }
    } else if matches!(f.ty, RustType::Option(_)) {
        quote! { #[serde(default, skip_serializing_if = "Option::is_none")] }
    } else {
        TokenStream::new()
    };
    let fdoc = doc_attr(&f.doc);
    quote! { #fdoc #rename #serde_attr pub #name: #ty }
}

fn box_self_refs(t: &RustType, self_name: &str) -> RustType {
    match t {
        RustType::Named(n) if n == self_name => RustType::Box(Box::new(t.clone())),
        RustType::Option(i) => RustType::Option(Box::new(box_self_refs(i, self_name))),
        // Vec already heap-allocates; leave element as-is.
        other => other.clone(),
    }
}

fn emit_rust_type(t: &RustType) -> TokenStream {
    match t {
        RustType::String => quote! { String },
        RustType::Bool => quote! { bool },
        RustType::I64 => quote! { i64 },
        RustType::F64 => quote! { f64 },
        RustType::Timestamp => quote! { polar_runtime::Timestamp },
        RustType::Value => quote! { serde_json::Value },
        RustType::Metadata => quote! { polar_runtime::Metadata },
        RustType::Named(n) => {
            let id = format_ident!("{}", n);
            quote! { #id }
        }
        RustType::Option(inner) => {
            let i = emit_rust_type(inner);
            quote! { Option<#i> }
        }
        RustType::Vec(inner) => {
            let i = emit_rust_type(inner);
            quote! { Vec<#i> }
        }
        RustType::Map(inner) => {
            let i = emit_rust_type(inner);
            quote! { std::collections::HashMap<String, #i> }
        }
        RustType::Box(inner) => {
            let i = emit_rust_type(inner);
            quote! { Box<#i> }
        }
    }
}

/// Like `emit_rust_type` but prefixes `Named` types with `types::`.
fn emit_api_type(t: &RustType) -> TokenStream {
    match t {
        RustType::Named(n) => {
            let id = format_ident!("{}", n);
            quote! { types::#id }
        }
        RustType::Option(inner) => {
            let i = emit_api_type(inner);
            quote! { Option<#i> }
        }
        RustType::Vec(inner) => {
            let i = emit_api_type(inner);
            quote! { Vec<#i> }
        }
        RustType::Map(inner) => {
            let i = emit_api_type(inner);
            quote! { std::collections::HashMap<String, #i> }
        }
        RustType::Box(inner) => {
            let i = emit_api_type(inner);
            quote! { Box<#i> }
        }
        // scalars and polar_runtime types delegate to the base renderer
        other => emit_rust_type(other),
    }
}

/// Returns true when a type is a simple scalar that implements `ToString` without
/// requiring any extra machinery.
fn is_scalar(t: &RustType) -> bool {
    matches!(
        t,
        RustType::String | RustType::Bool | RustType::I64 | RustType::F64 | RustType::Timestamp
    )
}

/// Sanitize an arbitrary string (e.g. `page[number]`, `metadata[key]`) into a
/// valid Rust identifier: replace all non-alphanumeric chars with `_`, prefix
/// with `_` if it starts with a digit, and raw-ident-escape keywords.
fn sanitize_ident(s: &str) -> proc_macro2::Ident {
    let mut out = String::with_capacity(s.len());
    for ch in s.chars() {
        if ch.is_ascii_alphanumeric() || ch == '_' {
            out.push(ch);
        } else {
            out.push('_');
        }
    }
    if out.is_empty() {
        out.push('_');
    }
    if out
        .chars()
        .next()
        .map(|c| c.is_ascii_digit())
        .unwrap_or(false)
    {
        out.insert(0, '_');
    }
    if RUST_KEYWORDS.contains(&out.as_str()) {
        format_ident!("r#{}", out)
    } else {
        format_ident!("{}", out)
    }
}

/// Collect the `{wire}` placeholder names from a path string in left-to-right
/// order, e.g. `/v1/users/{user_id}/orders/{order_id}` → ["user_id", "order_id"].
fn path_placeholder_names(path: &str) -> Vec<&str> {
    let mut names = Vec::new();
    let mut rest = path;
    while let Some(open) = rest.find('{') {
        rest = &rest[open + 1..];
        if let Some(close) = rest.find('}') {
            names.push(&rest[..close]);
            rest = &rest[close + 1..];
        }
    }
    names
}

fn emit_params_struct(tag: &str, method_name: &str, params: &[Param]) -> TokenStream {
    let struct_name = format_ident!("{}{}Params", tag, to_pascal(method_name));
    let fields: Vec<TokenStream> = params
        .iter()
        .map(|p| {
            let ident = sanitize_ident(&p.name);
            // Only scalars go as their native type; others become String.
            let base_ty = if is_scalar(&p.ty) {
                emit_rust_type(&p.ty)
            } else {
                quote! { String }
            };
            let ty = if p.required {
                base_ty
            } else {
                quote! { Option<#base_ty> }
            };
            quote! { pub #ident: #ty }
        })
        .collect();

    let pairs: Vec<TokenStream> = params
        .iter()
        .map(|p| {
            let ident = sanitize_ident(&p.name);
            let wire = &p.wire;
            if p.required {
                quote! { out.push((#wire.to_string(), self.#ident.to_string())); }
            } else {
                quote! {
                    if let Some(ref v) = self.#ident {
                        out.push((#wire.to_string(), v.to_string()));
                    }
                }
            }
        })
        .collect();

    quote! {
        #[derive(Clone, Default)]
        pub struct #struct_name {
            #(#fields),*
        }

        impl #struct_name {
            pub fn to_pairs(&self) -> Vec<(String, String)> {
                let mut out = Vec::new();
                #(#pairs)*
                out
            }
        }
    }
}

/// Renders the `resp.pagination.max_page` access expression as a `u32`,
/// adapting for the actual field type (i64, Option<i64>, etc.).
fn max_page_access_expr(ty: &RustType) -> TokenStream {
    match ty {
        RustType::I64 | RustType::F64 => quote! { resp.pagination.max_page as u32 },
        RustType::Option(inner) => match inner.as_ref() {
            RustType::I64 | RustType::F64 => {
                quote! { resp.pagination.max_page.unwrap_or(1) as u32 }
            }
            _ => quote! { resp.pagination.max_page.unwrap_or(1) as u32 },
        },
        _ => quote! { resp.pagination.max_page as u32 },
    }
}

/// Returns `Some((item_type, max_page_expr))` when the op qualifies as a page-based list:
/// GET with a `page` query param, response is a struct with `items: Vec<Item>` and
/// a `pagination` struct that has a `max_page` field.
fn list_item_type(ir: &Ir, op: &Operation) -> Option<(RustType, TokenStream)> {
    if op.http_method != "GET" {
        return None;
    }
    if !op.query_params.iter().any(|p| p.wire == "page") {
        return None;
    }

    let resp_name = match &op.response {
        RustType::Named(n) => n.as_str(),
        _ => return None,
    };

    let resp_def = ir.types.iter().find(|t| t.name == resp_name)?;
    let resp_fields = match &resp_def.kind {
        TypeKind::Struct(fields) => fields,
        _ => return None,
    };

    let items_field = resp_fields.iter().find(|f| f.name == "items")?;
    let item_ty = match &items_field.ty {
        RustType::Vec(inner) => *inner.clone(),
        _ => return None,
    };

    let pag_field = resp_fields.iter().find(|f| f.name == "pagination")?;
    let pag_name = match &pag_field.ty {
        RustType::Named(n) => n.as_str(),
        _ => return None,
    };

    let pag_def = ir.types.iter().find(|t| t.name == pag_name)?;
    let pag_fields = match &pag_def.kind {
        TypeKind::Struct(fields) => fields,
        _ => return None,
    };

    let max_page_field = pag_fields.iter().find(|f| f.name == "max_page")?;
    let max_page_expr = max_page_access_expr(&max_page_field.ty);

    Some((item_ty, max_page_expr))
}

fn emit_stream_method(
    op: &Operation,
    tag: &str,
    item_ty: &RustType,
    max_page_expr: &TokenStream,
) -> TokenStream {
    let stream_ident = format_ident!("{}_stream", op.method_name);
    let params_struct_ident = format_ident!("{}{}Params", tag, to_pascal(&op.method_name));
    let item_ty_tokens = emit_api_type(item_ty);
    let resp_ty_tokens = emit_api_type(&op.response);

    let placeholder_names = path_placeholder_names(&op.path);

    let path_args: Vec<TokenStream> = placeholder_names
        .iter()
        .map(|wire| {
            let param = op.path_params.iter().find(|p| p.wire == *wire);
            let ident = match param {
                Some(p) => sanitize_ident(&p.name),
                None => sanitize_ident(wire),
            };
            quote! { #ident: &str }
        })
        .collect();

    // Capture path params as owned Strings before the paginate closure.
    let path_captures: Vec<TokenStream> = placeholder_names
        .iter()
        .map(|wire| {
            let param = op.path_params.iter().find(|p| p.wire == *wire);
            let ident = match param {
                Some(p) => sanitize_ident(&p.name),
                None => sanitize_ident(wire),
            };
            let owned = format_ident!("{}_owned__", ident);
            quote! { let #owned = #ident.to_string(); }
        })
        .collect();

    // Path binding inside the closure body: static literal or format! from owned captures.
    let path_binding_in_closure: TokenStream = if placeholder_names.is_empty() {
        let lit = syn::LitStr::new(&op.path, proc_macro2::Span::call_site());
        quote! { let path__ = #lit; }
    } else {
        let fmt_str = {
            let mut s = op.path.clone();
            for name in &placeholder_names {
                s = s.replacen(&format!("{{{name}}}"), "{}", 1);
            }
            s
        };
        let fmt_lit = syn::LitStr::new(&fmt_str, proc_macro2::Span::call_site());
        let owned_idents: Vec<proc_macro2::Ident> = placeholder_names
            .iter()
            .map(|wire| {
                let param = op.path_params.iter().find(|p| p.wire == *wire);
                let ident = match param {
                    Some(p) => sanitize_ident(&p.name),
                    None => sanitize_ident(wire),
                };
                format_ident!("{}_owned__", ident)
            })
            .collect();
        quote! { let path__ = format!(#fmt_lit, #(#owned_idents),*); }
    };

    quote! {
        pub fn #stream_ident(&self, #(#path_args,)* params: &#params_struct_ident)
            -> impl polar_runtime::Stream<Item = Result<#item_ty_tokens, polar_runtime::Error>> + '_
        {
            let client = self.client.clone();
            #(#path_captures)*
            let base = params.to_pairs();
            polar_runtime::paginate(move |page| {
                let client = client.clone();
                #path_binding_in_closure
                let mut q: Vec<(String, String)> = base.iter().filter(|(k, _)| k != "page").cloned().collect();
                q.push(("page".to_string(), page.to_string()));
                async move {
                    let resp: #resp_ty_tokens = client
                        .request(polar_runtime::Method::GET, &path__, &q, None::<&()>)
                        .await?;
                    Ok(polar_runtime::Page { items: resp.items, max_page: #max_page_expr })
                }
            })
        }
    }
}

fn emit_tag_impl(tag: &str, ops: &[&Operation], ir: &Ir) -> TokenStream {
    let tag_ident = format_ident!("{}", tag);

    let mut methods: Vec<TokenStream> = Vec::new();
    for op in ops {
        let method_ident = if RUST_KEYWORDS.contains(&op.method_name.as_str()) {
            format_ident!("r#{}", op.method_name)
        } else {
            format_ident!("{}", op.method_name)
        };

        // Build path format string and ordered ident list matching placeholder order
        let placeholder_names = path_placeholder_names(&op.path);
        let mut fmt_str = op.path.clone();
        for name in &placeholder_names {
            fmt_str = fmt_str.replacen(&format!("{{{name}}}"), "{}", 1);
        }

        // Map placeholder wire names to their param idents (by wire name match)
        let path_format_args: Vec<proc_macro2::Ident> = placeholder_names
            .iter()
            .map(|wire| {
                // Find the param whose wire == *wire; fall back to sanitized wire name
                let param = op.path_params.iter().find(|p| p.wire == *wire);
                match param {
                    Some(p) => sanitize_ident(&p.name),
                    None => sanitize_ident(wire),
                }
            })
            .collect();

        // Function args: path params (by name ident, type &str always for strings)
        let path_args: Vec<TokenStream> = placeholder_names
            .iter()
            .map(|wire| {
                let param = op.path_params.iter().find(|p| p.wire == *wire);
                let ident = match param {
                    Some(p) => sanitize_ident(&p.name),
                    None => sanitize_ident(wire),
                };
                // Path params are always &str
                quote! { #ident: &str }
            })
            .collect();

        // Query params argument
        let has_query = !op.query_params.is_empty();
        let params_struct_ident = format_ident!("{}{}Params", tag, to_pascal(&op.method_name));
        let query_arg: TokenStream = if has_query {
            quote! { params: &#params_struct_ident, }
        } else {
            TokenStream::new()
        };

        // Request body argument
        let body_arg: TokenStream = match &op.request_body {
            Some(ty) => {
                let t = emit_api_type(ty);
                quote! { body: &#t, }
            }
            None => TokenStream::new(),
        };
        let body_expr: TokenStream = match &op.request_body {
            Some(_) => quote! { Some(body) },
            None => quote! { None::<&()> },
        };

        let response_ty = emit_api_type(&op.response);

        let http_method = format_ident!("{}", op.http_method);

        // Doc comment
        let doc = doc_attr(&op.doc);

        // Build the path binding: `let path = ...;` assigned to a short local
        // so the self.client.request(...) call fits on one line.
        let path_binding: TokenStream = if path_format_args.is_empty() {
            let lit = syn::LitStr::new(&fmt_str, proc_macro2::Span::call_site());
            quote! { let path__ = #lit; }
        } else {
            let fmt_lit = syn::LitStr::new(&fmt_str, proc_macro2::Span::call_site());
            quote! { let path__ = format!(#fmt_lit, #(#path_format_args),*); }
        };

        // Build query binding for query-bearing ops so the call stays compact
        let query_binding: TokenStream = if has_query {
            quote! { let q__ = params.to_pairs(); }
        } else {
            TokenStream::new()
        };
        let query_ref: TokenStream = if has_query {
            quote! { &q__ }
        } else {
            quote! { &[] }
        };

        methods.push(quote! {
            #doc
            pub async fn #method_ident(&self, #(#path_args,)* #query_arg #body_arg) -> Result<#response_ty, polar_runtime::Error> {
                #path_binding
                #query_binding
                self.client.request(polar_runtime::Method::#http_method, &path__, #query_ref, #body_expr).await
            }
        });

        // Emit `_stream` in addition for qualifying page-based list ops.
        if let Some((item_ty, max_page_expr)) = list_item_type(ir, op) {
            methods.push(emit_stream_method(op, tag, &item_ty, &max_page_expr));
        }
    }

    quote! {
        pub struct #tag_ident<'a> {
            client: &'a Client,
        }

        impl<'a> #tag_ident<'a> {
            pub fn new(client: &'a Client) -> Self {
                Self { client }
            }
            #(#methods)*
        }
    }
}

pub fn emit_operations(ir: &Ir) -> String {
    let mut items = TokenStream::new();

    // Params structs (for ops with query params)
    for op in &ir.operations {
        if !op.query_params.is_empty() {
            items.extend(emit_params_struct(
                &op.tag,
                &op.method_name,
                &op.query_params,
            ));
        }
    }

    // Group ops by tag, preserving sorted order
    let mut tags: Vec<&str> = Vec::new();
    for op in &ir.operations {
        if !tags.contains(&op.tag.as_str()) {
            tags.push(&op.tag);
        }
    }

    for tag in &tags {
        let ops: Vec<&Operation> = ir.operations.iter().filter(|o| o.tag == *tag).collect();
        items.extend(emit_tag_impl(tag, &ops, ir));
    }

    // Resources trait
    let trait_methods: Vec<TokenStream> = tags
        .iter()
        .map(|tag| {
            let tag_ident = format_ident!("{}", tag);
            let accessor_ident = {
                // Use the accessor from the first op for this tag
                let accessor = ir
                    .operations
                    .iter()
                    .find(|o| o.tag == *tag)
                    .map(|o| o.accessor.as_str())
                    .unwrap_or(tag);
                if RUST_KEYWORDS.contains(&accessor) {
                    format_ident!("r#{}", accessor)
                } else {
                    format_ident!("{}", accessor)
                }
            };
            quote! {
                fn #accessor_ident(&self) -> #tag_ident<'_>;
            }
        })
        .collect();

    let impl_methods: Vec<TokenStream> = tags
        .iter()
        .map(|tag| {
            let tag_ident = format_ident!("{}", tag);
            let accessor_ident = {
                let accessor = ir
                    .operations
                    .iter()
                    .find(|o| o.tag == *tag)
                    .map(|o| o.accessor.as_str())
                    .unwrap_or(tag);
                if RUST_KEYWORDS.contains(&accessor) {
                    format_ident!("r#{}", accessor)
                } else {
                    format_ident!("{}", accessor)
                }
            };
            quote! {
                fn #accessor_ident(&self) -> #tag_ident<'_> {
                    #tag_ident::new(self)
                }
            }
        })
        .collect();

    items.extend(quote! {
        pub trait Resources {
            #(#trait_methods)*
        }

        impl Resources for Client {
            #(#impl_methods)*
        }
    });

    let file: syn::File = syn::parse2(quote! {
        #![allow(clippy::all, dead_code)]
        #items
    })
    .expect("emit_operations: emitted tokens parse as a file");

    let body = prettyplease::unparse(&file);
    let banner = "// Generated by `cargo xtask generate`. DO NOT EDIT.\n";
    let uses = "use polar_runtime::Client;\nuse crate::types;\n";
    match body.split_once('\n') {
        Some((attr, rest)) if attr.starts_with("#![") => format!("{attr}\n{banner}{uses}{rest}"),
        _ => format!("{banner}{uses}{body}"),
    }
}
